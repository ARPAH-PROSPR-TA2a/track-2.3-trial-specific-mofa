.load_or_validate_mofa <- function(mofa_obj) {
  if (is.character(mofa_obj)) {
    if (length(mofa_obj) != 1L || is.na(mofa_obj) || !nzchar(mofa_obj)) {
      stop("mofa_obj must be a single non-empty file path.", call. = FALSE)
    }
    if (!file.exists(mofa_obj)) {
      stop("MOFA model file does not exist: ", mofa_obj, call. = FALSE)
    }
    return(MOFA2::load_model(mofa_obj))
  }

  if (!methods::is(mofa_obj, "MOFA")) {
    stop(
      "mofa_obj must be either a valid MOFA model file path or a fitted MOFA object.",
      call. = FALSE
    )
  }

  mofa_obj
}

.resolve_requested_names <- function(requested, available, label) {
  if (length(requested) == 1L && identical(requested, "all")) {
    return(available)
  }

  missing <- setdiff(requested, available)
  if (length(missing) > 0L) {
    warning(sprintf(
      "Ignoring unknown %s: %s",
      label,
      paste(missing, collapse = ", ")
    ))
  }

  selected <- intersect(requested, available)
  if (length(selected) == 0L) {
    stop("No requested ", label, " are available.", call. = FALSE)
  }

  selected
}

.normalize_mofa_data_list <- function(mofa_data, selected_views) {
  # MOFA2::get_data() may return a list of matrices, or a nested list by group.
  # This helper assumes no groups and extracts a features x samples matrix per view.
  out <- list()

  for (view_name in selected_views) {
    x <- NULL

    if (is.list(mofa_data) && !is.null(mofa_data[[view_name]])) {
      x <- mofa_data[[view_name]]
    }

    # Handle possible nested no-group structure: view -> group -> matrix.
    if (is.list(x) && !is.data.frame(x) && !is.matrix(x)) {
      if (length(x) != 1L) {
        stop(
          "MOFA data for view '", view_name,
          "' appears to contain multiple groups, but this implementation assumes no groups.",
          call. = FALSE
        )
      }
      x <- x[[1L]]
    }

    if (is.null(x)) {
      stop("Could not retrieve MOFA training data for view '", view_name, "'.", call. = FALSE)
    }

    out[[view_name]] <- x
  }

  out
}

.normalize_mofa_factor_matrix <- function(mofa_factors) {
  # MOFA2::get_factors() commonly returns a list with one matrix when no groups
  # are present. The matrix should be samples x factors.
  if (is.matrix(mofa_factors) || is.data.frame(mofa_factors)) {
    return(as.matrix(mofa_factors))
  }

  if (is.list(mofa_factors)) {
    if (length(mofa_factors) != 1L) {
      stop(
        "MOFA factor output appears to contain multiple groups, but this implementation assumes no groups.",
        call. = FALSE
      )
    }
    return(as.matrix(mofa_factors[[1L]]))
  }

  stop("Could not convert MOFA factor output to a samples x factors matrix.", call. = FALSE)
}

.as_numeric_matrix <- function(x, object_name = "object") {
  if (!(is.matrix(x) || is.data.frame(x))) {
    stop(object_name, " must be a matrix or data frame.", call. = FALSE)
  }

  x_mat <- as.matrix(x)

  if (!is.numeric(x_mat)) {
    stop(object_name, " must contain only numeric values.", call. = FALSE)
  }

  if (is.null(rownames(x_mat)) || anyNA(rownames(x_mat)) || any(rownames(x_mat) == "")) {
    stop(object_name, " must have non-empty row names.", call. = FALSE)
  }

  if (is.null(colnames(x_mat)) || anyNA(colnames(x_mat)) || any(colnames(x_mat) == "")) {
    stop(object_name, " must have non-empty column names.", call. = FALSE)
  }

  x_mat
}

.drop_all_na_sample_columns <- function(x, object_name = "object") {
  # Input matrices are expected to be features x samples. Columns whose values
  # are all NA represent samples missing entirely from that data view; these are
  # valid in MOFA input matrices but unusable for supervised prediction.
  all_na_sample <- apply(x, 2, function(z) all(is.na(z)))

  if (any(all_na_sample)) {
    message(
      object_name,
      ": dropping ",
      sum(all_na_sample),
      " all-NA sample column(s): ",
      paste(colnames(x)[all_na_sample], collapse = ", ")
    )
    x <- x[, !all_na_sample, drop = FALSE]
  }

  if (ncol(x) == 0L) {
    stop(object_name, " has no sample columns remaining after dropping all-NA columns.", call. = FALSE)
  }

  x
}

.train_one_view_factor_model <- function(
  view_name,
  factor_name,
  X_view_features_by_samples,
  Y,
  outcome_type,
  n_repeats,
  train_frac,
  split_seeds,
  job_seed,
  alpha,
  lambda_choice,
  standardize,
  nfolds,
  min_samples,
  min_features
) {
  X_view_features_by_samples <- .as_numeric_matrix(
    X_view_features_by_samples,
    object_name = paste0("MOFA data view '", view_name, "'")
  )

  # MOFA input views may be padded with all-NA sample columns, for example when
  # methods.R::fillEmptyCols() was used so that MOFA sees the complete sample
  # universe even when a view has missing measurements. For supervised LASSO
  # training, such columns represent samples absent from this view and must be
  # removed before any finite-value or variance checks.
  X_view_features_by_samples <- .drop_all_na_sample_columns(
    X_view_features_by_samples,
    object_name = paste0("MOFA data view '", view_name, "'")
  )

  # Transpose to samples x features for glmnet.
  X_view <- t(X_view_features_by_samples)

  if (is.null(rownames(X_view)) || any(rownames(X_view) == "")) {
    stop("Training data for view '", view_name, "' lacks sample names.", call. = FALSE)
  }

  # Align samples between the selected view and the MOFA factor matrix.
  common_samples <- intersect(rownames(X_view), rownames(Y))
  if (length(common_samples) < min_samples) {
    warning(sprintf(
      "Skipping view '%s', factor '%s': only %d matched samples.",
      view_name, factor_name, length(common_samples)
    ))
    return(NULL)
  }

  X_full <- X_view[common_samples, , drop = FALSE]
  y_full <- Y[common_samples, factor_name]

  if (any(!is.finite(y_full))) {
    warning(sprintf(
      "Skipping view '%s', factor '%s': factor values contain non-finite values.",
      view_name, factor_name
    ))
    return(NULL)
  }

  # Drop features with non-finite values or zero variance across all matched
  # training samples. We do this once for the final model. Internal repeats also
  # remove zero-variance features within each split.
  finite_feature <- apply(X_full, 2, function(z) all(is.finite(z)))
  X_full <- X_full[, finite_feature, drop = FALSE]

  nzv_full <- apply(X_full, 2, stats::var, na.rm = TRUE) > 0
  X_full <- X_full[, nzv_full, drop = FALSE]

  if (ncol(X_full) < min_features) {
    warning(sprintf(
      "Skipping view '%s', factor '%s': only %d usable features.",
      view_name, factor_name, ncol(X_full)
    ))
    return(NULL)
  }

  # Perform repeated internal train/test validation.
  internal <- .run_repeated_internal_cv(
    X_full = X_full,
    y_full = y_full,
    outcome_type = outcome_type,
    n_repeats = n_repeats,
    train_frac = train_frac,
    split_seeds = split_seeds,
    alpha = alpha,
    lambda_choice = lambda_choice,
    standardize = standardize,
    nfolds = nfolds,
    min_features = min_features
  )

  # Fit the final model on all matched samples. The job-specific seed makes
  # glmnet's internal fold assignment reproducible regardless of whether jobs are
  # executed serially or in parallel.
  set.seed(job_seed)
  family_type <- if (outcome_type == "binary") "binomial" else "gaussian"
  final_model <- glmnet::cv.glmnet(
    x = X_full,
    y = y_full,
    alpha = alpha,
    family = family_type,
    standardize = standardize,
    nfolds = min(nfolds, nrow(X_full))
  )

  nonzero <- .extract_nonzero_coefficients(final_model, lambda_choice)

  list(
    view_name = view_name,
    factor_name = factor_name,
    outcome_type = outcome_type,
    n_samples = nrow(X_full),
    n_features = ncol(X_full),
    samples = rownames(X_full),
    features = colnames(X_full),
    internal_cv = internal,
    final_model = final_model,
    lambda_choice = lambda_choice,
    nonzero_coefficients = nonzero
  )
}

.run_repeated_internal_cv <- function(
  X_full,
  y_full,
  outcome_type,
  n_repeats,
  train_frac,
  split_seeds,
  alpha,
  lambda_choice,
  standardize,
  nfolds,
  min_features
) {
  metrics_by_repeat <- list()
  predictions_by_repeat <- list()

  sample_ids <- rownames(X_full)
  family_type <- if (outcome_type == "binary") "binomial" else "gaussian"

  for (i in seq_len(n_repeats)) {
    set.seed(split_seeds[i])

    train_ids <- sample(sample_ids, size = floor(train_frac * length(sample_ids)))
    test_ids <- setdiff(sample_ids, train_ids)

    X_train <- X_full[train_ids, , drop = FALSE]
    y_train <- y_full[train_ids]
    X_test <- X_full[test_ids, , drop = FALSE]
    y_test <- y_full[test_ids]

    # Remove features with zero variance in the training split only.
    nzv <- apply(X_train, 2, stats::var, na.rm = TRUE) > 0
    X_train <- X_train[, nzv, drop = FALSE]
    X_test <- X_test[, colnames(X_train), drop = FALSE]

    if (ncol(X_train) < min_features) {
      warning("Skipping internal repeat ", i, ": too few non-zero-variance features.")
      next
    }

    fit <- glmnet::cv.glmnet(
      x = X_train,
      y = y_train,
      alpha = alpha,
      family = family_type,
      standardize = standardize,
      nfolds = min(nfolds, nrow(X_train))
    )

    pred_type <- if (outcome_type == "binary") "response" else "link"
    pred <- stats::predict(fit, newx = X_test, s = lambda_choice, type = pred_type)
    pred <- as.numeric(pred)
    names(pred) <- test_ids

    metrics <- .compute_prediction_metrics(y_test, pred, outcome_type)
    metrics$repeat_id <- i
    metrics$n_train <- length(train_ids)
    metrics$n_test <- length(test_ids)
    metrics$n_features_used <- ncol(X_train)
    metrics$n_nonzero <- nrow(.extract_nonzero_coefficients(fit, lambda_choice))

    metrics_by_repeat[[length(metrics_by_repeat) + 1L]] <- metrics
    predictions_by_repeat[[length(predictions_by_repeat) + 1L]] <- data.frame(
      repeat_id = i,
      sample_id = test_ids,
      observed = as.numeric(y_test),
      predicted = as.numeric(pred),
      stringsAsFactors = FALSE
    )
  }

  metrics_df <- .rbind_fill(metrics_by_repeat)
  predictions_df <- .rbind_fill(predictions_by_repeat)
  metrics_summary <- .summarize_metrics(metrics_df)

  list(
    metrics_by_repeat = metrics_df,
    metrics_summary = metrics_summary,
    predictions_by_repeat = predictions_df
  )
}

.compute_prediction_metrics <- function(observed, predicted, outcome_type) {
  observed <- as.numeric(observed)
  predicted <- as.numeric(predicted)

  if (outcome_type == "binary") {
    pred_class <- as.numeric(predicted > 0.5)
    return(data.frame(
      accuracy = mean(pred_class == observed),
      rmse = sqrt(mean((observed - predicted)^2)),
      mae = mean(abs(observed - predicted)),
      stringsAsFactors = FALSE
    ))
  }

  ss_total <- sum((observed - mean(observed))^2)
  ss_resid <- sum((observed - predicted)^2)
  r_squared <- if (ss_total > 0) 1 - ss_resid / ss_total else NA_real_

  pearson <- suppressWarnings(stats::cor(observed, predicted, method = "pearson"))
  spearman <- suppressWarnings(stats::cor(observed, predicted, method = "spearman"))
  rmse <- sqrt(mean((observed - predicted)^2))
  mae <- mean(abs(observed - predicted))

  slope <- NA_real_
  intercept <- NA_real_
  if (length(unique(predicted)) > 1L) {
    lm_fit <- stats::lm(predicted ~ observed)
    intercept <- unname(stats::coef(lm_fit)[1])
    slope <- unname(stats::coef(lm_fit)[2])
  }

  data.frame(
    pearson = pearson,
    spearman = spearman,
    r_squared = r_squared,
    rmse = rmse,
    mae = mae,
    slope = slope,
    intercept = intercept,
    stringsAsFactors = FALSE
  )
}

.summarize_metrics <- function(metrics_df) {
  if (nrow(metrics_df) == 0L) {
    return(data.frame())
  }

  exclude <- c("repeat_id", "n_train", "n_test", "n_features_used", "n_nonzero")
  metric_names <- setdiff(names(metrics_df), exclude)
  metric_names <- metric_names[vapply(metrics_df[metric_names], is.numeric, logical(1))]

  rows <- lapply(metric_names, function(metric) {
    z <- metrics_df[[metric]]
    data.frame(
      metric = metric,
      mean = mean(z, na.rm = TRUE),
      sd = stats::sd(z, na.rm = TRUE),
      min = min(z, na.rm = TRUE),
      median = stats::median(z, na.rm = TRUE),
      max = max(z, na.rm = TRUE),
      stringsAsFactors = FALSE
    )
  })

  do.call(rbind, rows)
}

.extract_nonzero_coefficients <- function(model, lambda_choice) {
  coef_mat <- as.matrix(stats::coef(model, s = lambda_choice))
  coef_vec <- coef_mat[, 1]

  # Remove intercept and zero coefficients.
  coef_vec <- coef_vec[names(coef_vec) != "(Intercept)"]
  coef_vec <- coef_vec[coef_vec != 0]

  if (length(coef_vec) == 0L) {
    return(data.frame(feature = character(), coefficient = numeric()))
  }

  out <- data.frame(
    feature = names(coef_vec),
    coefficient = as.numeric(coef_vec),
    abs_coefficient = abs(as.numeric(coef_vec)),
    stringsAsFactors = FALSE
  )

  out[order(out$abs_coefficient, decreasing = TRUE), , drop = FALSE]
}

.collect_nonzero_coefficients <- function(training_results) {
  rows <- list()
  idx <- 1L

  for (view_name in names(training_results$results)) {
    for (factor_name in names(training_results$results[[view_name]])) {
      res <- training_results$results[[view_name]][[factor_name]]
      if (is.null(res)) next
      coef_df <- res$nonzero_coefficients
      if (nrow(coef_df) == 0L) next

      coef_df$view <- view_name
      coef_df$factor <- factor_name
      coef_df <- coef_df[, c("view", "factor", "feature", "coefficient", "abs_coefficient")]
      rows[[idx]] <- coef_df
      idx <- idx + 1L
    }
  }

  if (length(rows) == 0L) {
    return(data.frame(
      view = character(),
      factor = character(),
      feature = character(),
      coefficient = numeric(),
      abs_coefficient = numeric(),
      stringsAsFactors = FALSE
    ))
  }

  do.call(rbind, rows)
}

.rbind_fill <- function(rows) {
  rows <- rows[!vapply(rows, is.null, logical(1))]
  if (length(rows) == 0L) {
    return(data.frame())
  }

  all_names <- unique(unlist(lapply(rows, names)))
  filled <- lapply(rows, function(x) {
    missing <- setdiff(all_names, names(x))
    for (m in missing) x[[m]] <- NA
    x[, all_names, drop = FALSE]
  })

  do.call(rbind, filled)
}

.training_metrics_long <- function(training_results) {
  # Build one row per view/factor/metric combination. The mean and confidence
  # interval are computed from the repeated internal validation splits.
  rows <- list()
  idx <- 1L

  metadata_cols <- c("repeat_id", "n_train", "n_test", "n_features_used", "n_nonzero")

  for (view_name in names(training_results$results)) {
    for (factor_name in names(training_results$results[[view_name]])) {
      res <- training_results$results[[view_name]][[factor_name]]
      if (is.null(res)) next

      metrics_df <- res$internal_cv$metrics_by_repeat
      if (is.null(metrics_df) || nrow(metrics_df) == 0L) next

      metric_names <- setdiff(names(metrics_df), metadata_cols)
      metric_names <- metric_names[vapply(metrics_df[metric_names], is.numeric, logical(1))]

      for (metric_name in metric_names) {
        z <- metrics_df[[metric_name]]
        z <- z[is.finite(z)]
        n <- length(z)
        if (n == 0L) next

        metric_mean <- mean(z)
        metric_sd <- if (n > 1L) stats::sd(z) else NA_real_
        metric_se <- if (n > 1L) metric_sd / sqrt(n) else NA_real_
        ci_half_width <- if (n > 1L) stats::qt(0.975, df = n - 1L) * metric_se else NA_real_

        rows[[idx]] <- data.frame(
          view = view_name,
          factor = factor_name,
          factor_index = .factor_sort_key(factor_name),
          metric = metric_name,
          mean = metric_mean,
          sd = metric_sd,
          n = n,
          se = metric_se,
          ci_low = if (is.na(ci_half_width)) NA_real_ else metric_mean - ci_half_width,
          ci_high = if (is.na(ci_half_width)) NA_real_ else metric_mean + ci_half_width,
          stringsAsFactors = FALSE
        )
        idx <- idx + 1L
      }
    }
  }

  if (length(rows) == 0L) {
    return(data.frame(
      view = character(),
      factor = character(),
      factor_index = numeric(),
      metric = character(),
      mean = numeric(),
      sd = numeric(),
      n = integer(),
      se = numeric(),
      ci_low = numeric(),
      ci_high = numeric(),
      stringsAsFactors = FALSE
    ))
  }

  out <- do.call(rbind, rows)
  out <- out[order(out$metric, out$factor_index, out$factor, out$view), , drop = FALSE]
  rownames(out) <- NULL
  out
}

.factor_sort_key <- function(factor_name) {
  # Sort factor labels such as Factor1, Factor 1, or factor_1 by their numeric
  # suffix. Non-standard names fall back to their appearance order via Inf.
  digits <- regmatches(factor_name, gregexpr("[0-9]+", factor_name))[[1]]
  if (length(digits) == 0L) return(Inf)
  as.numeric(digits[length(digits)])
}

.metric_plot_order <- function(metric_names) {
  preferred <- c(
    "pearson",
    "spearman",
    "r_squared",
    "rmse",
    "mae",
    "slope",
    "intercept",
    "accuracy"
  )
  c(intersect(preferred, metric_names), sort(setdiff(metric_names, preferred)))
}

.metric_label <- function(metric_name) {
  labels <- c(
    pearson = "Pearson correlation",
    spearman = "Spearman correlation",
    r_squared = "Out-of-sample R-squared",
    rmse = "RMSE",
    mae = "MAE",
    slope = "Prediction slope",
    intercept = "Prediction intercept",
    accuracy = "Accuracy"
  )
  if (metric_name %in% names(labels)) {
    return(unname(labels[[metric_name]]))
  }
  gsub("_", " ", metric_name)
}

.plot_training_metric <- function(plot_df, metric_name) {
  # Order the x-axis by numeric factor index while retaining the original factor
  # labels. Each data view is drawn as a separate colored line.
  factor_levels <- unique(plot_df$factor[order(plot_df$factor_index, plot_df$factor)])
  plot_df$factor <- factor(plot_df$factor, levels = factor_levels)

  y_label <- .metric_label(metric_name)

  p <- ggplot2::ggplot(
    plot_df,
    ggplot2::aes(x = factor, y = mean, group = view, color = view)
  ) +
    ggplot2::geom_line(linewidth = 0.7, na.rm = TRUE) +
    ggplot2::geom_point(size = 2.2, na.rm = TRUE) +
    ggplot2::geom_errorbar(
      ggplot2::aes(ymin = ci_low, ymax = ci_high),
      width = 0.15,
      linewidth = 0.45,
      na.rm = TRUE
    ) +
    ggplot2::labs(
      title = paste0(y_label, " by MOFA factor and data view"),
      subtitle = "Points show mean performance across repeated internal train/test splits; error bars show approximate 95% confidence intervals.",
      x = "MOFA factor",
      y = y_label,
      color = "Data view"
    ) +
    ggplot2::theme_bw(base_size = 12) +
    ggplot2::theme(
      plot.title = ggplot2::element_text(face = "bold", size = 15),
      plot.subtitle = ggplot2::element_text(size = 10),
      axis.text.x = ggplot2::element_text(angle = 45, hjust = 1, vjust = 1),
      legend.position = "bottom",
      panel.grid.minor = ggplot2::element_blank()
    )

  # Add a helpful reference line for metrics with natural zero baselines.
  if (metric_name %in% c("pearson", "spearman", "r_squared", "slope", "intercept")) {
    p <- p + ggplot2::geom_hline(yintercept = 0, linetype = "dashed", linewidth = 0.3)
  }

  p
}

