.top_nonzero_coefficients <- function(coef_df, top_n_features = 20) {
  if (nrow(coef_df) == 0L || !isTRUE(top_n_features > 0)) {
    return(coef_df[0, , drop = FALSE])
  }

  rows <- lapply(split(coef_df, list(coef_df$view, coef_df$factor), drop = TRUE), function(z) {
    z <- z[order(z$abs_coefficient, decreasing = TRUE), , drop = FALSE]
    utils::head(z, top_n_features)
  })

  out <- do.call(rbind, rows)
  rownames(out) <- NULL
  out
}

