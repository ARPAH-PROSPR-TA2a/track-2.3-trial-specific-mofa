# *****************************************************************************
# Train view-specific penalized-regression predictors of MOFA factor values.
#
# User-configurable settings are maintained in mofa_train_glm_parameters.R.
# The script loads the fitted MOFA model specified by mofa_res_fname, trains
# LASSO/elastic-net predictors, writes the predictor object to
# glm_model/mofa_glm_predictor.rds, and generates the training report in the
# same glm_model folder.
#
# Run from an R session as:
#
#   source("path_to_code/mofa_train_glm.R", local = TRUE, chdir = TRUE)
# 
# Alternatively, run the script from the command line:
#
#   Rscript.exe -e "source('path_to_code/mofa_train_glm.R', local = TRUE, 
#				chdir = TRUE)"
#
# *****************************************************************************

# Load user-configurable settings. Using local = TRUE keeps settings and helper
# functions scoped to the environment in which this script is sourced.
source("mofa_train_glm_parameters.R", local = TRUE)

#' Train LASSO/elastic-net predictors of MOFA factor values
#'
#' This function trains view-specific penalized regression models that predict
#' MOFA-derived factor values from the same preprocessed data views used to fit a
#' MOFA2 model. For each selected view and factor, the function performs repeated
#' internal train/test validation, summarizes prediction quality, and then fits a
#' final cv.glmnet model using all available training samples.
#'
#' The intended use is to evaluate whether a given MOFA factor can be reproduced
#' from a single molecular data view. If internal validation performance is poor,
#' the corresponding factor/view predictor should generally not be used for
#' external scoring.
#'
#' @param mofa_obj Either a fitted MOFA2 object generated by MOFA2::run_mofa(),
#'   or a character string giving the full path to a saved fitted MOFA2 model,
#'   such as a model.hdf5 file.
#' @param factors Character vector of factor names to evaluate, or "all" to use
#'   all factors in the MOFA object. Default is "all".
#' @param views Character vector of view names to evaluate, or "all" to use all
#'   views in the MOFA object. Default is "all".
#' @param outcome_type Currently only "continuous" is fully supported for MOFA
#'   factor prediction. "binary" is accepted for completeness but is not the
#'   recommended use case for continuous MOFA factor values.
#' @param n_repeats Number of repeated internal train/test splits. Default is 20.
#' @param train_frac Fraction of samples used for training in each internal
#'   split. Default is 0.7.
#' @param seed Optional integer seed used to generate repeat-specific seeds and
#'   final-model seeds. Default is NULL.
#' @param alpha Elastic-net mixing parameter passed to glmnet. alpha = 1 gives
#'   LASSO. Default is 1.
#' @param lambda_choice Which lambda to use for internal predictions, final
#'   predictions, and coefficient extraction. One of "lambda.min" or
#'   "lambda.1se". Default is "lambda.min".
#' @param standardize Logical passed to glmnet::cv.glmnet(). If TRUE, glmnet
#'   standardizes predictors internally using the training data. Default is TRUE.
#' @param nfolds Number of folds used inside cv.glmnet(). Default is 10.
#' @param min_samples Minimum number of matched samples required for a view/factor
#'   model. Default is 10.
#' @param min_features Minimum number of usable non-zero-variance features
#'   required for a view/factor model. Default is 2.
#' @param use_parallel Logical; if TRUE, train independent view/factor models in
#'   parallel using future.apply::future_lapply() with a multisession backend.
#'   This is portable across Windows, macOS, and Linux. Default is FALSE.
#' @param n_workers Number of parallel worker processes to use when
#'   use_parallel = TRUE. Default is max(1, parallel::detectCores() - 1).
#' @param verbose Logical; if TRUE, progress messages are printed. Default TRUE.
#'
#' @return A list of class "MofaFactorPredictor" containing settings, model
#'   metadata, and one result object for each view/factor combination. Each
#'   result includes internal validation metrics, held-out predictions, final
#'   model, selected features, and nonzero coefficients.
#'
#' @details
#' The function retrieves training data directly from the fitted MOFA object with
#' MOFA2::get_data() and factor values with MOFA2::get_factors(). This ensures
#' that supervised predictors are trained on the same preprocessed data matrix
#' that was used to fit MOFA. The function assumes that the MOFA object has no
#' groups.
#'
#' Parallelization is performed across independent view/factor combinations, for
#' example RNA/Factor1, RNA/Factor2, Proteomics/Factor1, and so on. The repeated
#' cross-validation loop inside each view/factor job is kept serial to avoid
#' nested parallelism and to keep random-number handling straightforward.
#'
#' Internal validation metrics for continuous factors include Pearson
#' correlation, Spearman correlation, out-of-sample R-squared, RMSE, MAE,
#' prediction slope, prediction intercept, and number of selected nonzero
#' features. Final models are trained on all matched samples for each view/factor
#' pair.
#'
#' @examples
#' \dontrun{
#' predictor <- trainMofaFactorPredictor(
#'   mofa_obj = "model.hdf5",
#'   factors = "all",
#'   views = "all",
#'   n_repeats = 20,
#'   train_frac = 0.7,
#'   use_parallel = TRUE,
#'   n_workers = 4
#' )
#' }
#'
#' @export
trainMofaFactorPredictor <- function(
  mofa_obj,
  factors = "all",
  views = "all",
  outcome_type = "continuous",
  n_repeats = 20,
  train_frac = 0.7,
  seed = NULL,
  alpha = 1,
  lambda_choice = c("lambda.min", "lambda.1se"),
  standardize = TRUE,
  nfolds = 10,
  min_samples = 10,
  min_features = 2,
  use_parallel = FALSE,
  n_workers = max(1L, parallel::detectCores() - 5L),
  verbose = TRUE
) {
  # Validate package dependencies early.
  requireNamespace("MOFA2", quietly = TRUE) ||
    stop("The MOFA2 package is required but is not installed.", call. = FALSE)
  requireNamespace("glmnet", quietly = TRUE) ||
    stop("The glmnet package is required but is not installed.", call. = FALSE)

  lambda_choice <- match.arg(lambda_choice)
  outcome_type <- match.arg(outcome_type, choices = c("continuous", "binary"))

  if (!is.logical(use_parallel) || length(use_parallel) != 1L || is.na(use_parallel)) {
    stop("use_parallel must be TRUE or FALSE.", call. = FALSE)
  }
  if (!is.numeric(n_workers) || length(n_workers) != 1L || is.na(n_workers) || n_workers < 1) {
    stop("n_workers must be a positive integer.", call. = FALSE)
  }
  n_workers <- as.integer(n_workers)

  if (use_parallel) {
    requireNamespace("future", quietly = TRUE) ||
      stop("The future package is required when use_parallel = TRUE.", call. = FALSE)
    requireNamespace("future.apply", quietly = TRUE) ||
      stop("The future.apply package is required when use_parallel = TRUE.", call. = FALSE)
  }

  # Load the MOFA model if the user supplied a file path.
  mofa_obj <- .load_or_validate_mofa(mofa_obj)

  # Extract model metadata.
  model_views <- MOFA2::views_names(mofa_obj)
  model_factors <- MOFA2::factors_names(mofa_obj)

  if (length(model_views) == 0L) {
    stop("The MOFA object contains no views.", call. = FALSE)
  }
  if (length(model_factors) == 0L) {
    stop("The MOFA object contains no factors.", call. = FALSE)
  }

  # Resolve requested views and factors.
  selected_views <- .resolve_requested_names(views, model_views, "views")
  selected_factors <- .resolve_requested_names(factors, model_factors, "factors")

  # Retrieve the preprocessed training data and factor values from the MOFA object.
  # For no-group MOFA objects, get_data() and get_factors() commonly return a
  # list with one matrix per view/group; helper functions below normalize this.
  mofa_data <- MOFA2::get_data(mofa_obj, views = selected_views, as.data.frame = FALSE)
  mofa_factors <- MOFA2::get_factors(mofa_obj, factors = selected_factors, as.data.frame = FALSE)

  X_by_view <- .normalize_mofa_data_list(mofa_data, selected_views)
  Y <- .normalize_mofa_factor_matrix(mofa_factors)

  # Keep only selected factor columns and validate that sample IDs are available.
  Y <- Y[, selected_factors, drop = FALSE]
  if (is.null(rownames(Y)) || anyNA(rownames(Y)) || any(rownames(Y) == "")) {
    stop("MOFA factor matrix must have non-empty sample IDs as row names.", call. = FALSE)
  }

  # Precompute seeds in the main process so that serial and parallel execution
  # use the same random-number plan. Each view/factor job gets its own final-model
  # seed; internal CV split seeds are also generated before any parallel workers
  # are launched.
  if (!is.null(seed)) {
    set.seed(seed)
  }
  split_seeds <- sample.int(.Machine$integer.max, n_repeats)

  jobs <- expand.grid(
    view_name = selected_views,
    factor_name = selected_factors,
    stringsAsFactors = FALSE
  )
  job_seeds <- sample.int(.Machine$integer.max, nrow(jobs))

  if (verbose) {
    message(
      "Training ", nrow(jobs), " view/factor model(s)",
      if (use_parallel) paste0(" using ", n_workers, " parallel worker(s).") else " serially."
    )
  }

  # A single worker job trains one independent view/factor model. This is the
  # natural unit of parallelization because no view/factor model depends on the
  # results of any other view/factor model.
  train_job <- function(job_index) {
    view_name <- jobs$view_name[[job_index]]
    factor_name <- jobs$factor_name[[job_index]]

    if (verbose) {
      message("Processing view/factor: ", view_name, " / ", factor_name)
    }

    .train_one_view_factor_model(
      view_name = view_name,
      factor_name = factor_name,
      X_view_features_by_samples = X_by_view[[view_name]],
      Y = Y,
      outcome_type = outcome_type,
      n_repeats = n_repeats,
      train_frac = train_frac,
      split_seeds = split_seeds,
      job_seed = job_seeds[[job_index]],
      alpha = alpha,
      lambda_choice = lambda_choice,
      standardize = standardize,
      nfolds = nfolds,
      min_samples = min_samples,
      min_features = min_features
    )
  }

  if (use_parallel) {
    # Save and restore the user's future plan so this function does not leave a
    # global parallel backend behind after it returns.
    old_plan <- future::plan()
    on.exit(future::plan(old_plan), add = TRUE)
    future::plan(future::multisession, workers = n_workers)

    job_results <- future.apply::future_lapply(
      X = seq_len(nrow(jobs)),
      FUN = train_job,
      future.seed = TRUE
    )
  } else {
    job_results <- lapply(seq_len(nrow(jobs)), train_job)
  }

  # Reassemble flat job results into the nested results[[view]][[factor]] form
  # used by downstream prediction and reporting functions.
  results <- setNames(vector("list", length(selected_views)), selected_views)
  for (view_name in selected_views) {
    results[[view_name]] <- list()
  }

  for (res in job_results) {
    if (is.null(res)) next
    results[[res$view_name]][[res$factor_name]] <- res
  }

  out <- list(
    settings = list(
      factors = selected_factors,
      views = selected_views,
      outcome_type = outcome_type,
      n_repeats = n_repeats,
      train_frac = train_frac,
      seed = seed,
      split_seeds = split_seeds,
      job_seeds = job_seeds,
      alpha = alpha,
      lambda_choice = lambda_choice,
      standardize = standardize,
      nfolds = nfolds,
      min_samples = min_samples,
      min_features = min_features,
      use_parallel = use_parallel,
      n_workers = if (use_parallel) n_workers else 1L
    ),
    model_info = list(
      views = model_views,
      factors = model_factors,
      n_views = length(model_views),
      n_factors = length(model_factors)
    ),
    results = results
  )

  class(out) <- c("MofaFactorPredictor", class(out))
  out
}

#' Generate a PDF report for MOFA factor predictor training results
#'
#' This function generates a landscape PDF report summarizing the internal
#' validation performance of view-specific MOFA factor predictors trained by
#' trainMofaFactorPredictor(). The report is generated with the base R PDF
#' graphics device and ggplot2, so it does not require pandoc, rmarkdown, or a
#' LaTeX installation.
#'
#' The report contains one line plot per training metric. In each plot, the
#' x-axis shows MOFA factors, and each colored line represents one data view.
#' For a given factor and view, the plotted point is the mean metric value over
#' repeated internal validation splits. When enough repeated estimates are
#' available, vertical error bars show an approximate 95 percent confidence
#' interval for the mean.
#'
#' @param training_results A "MofaFactorPredictor" object returned by
#'   trainMofaFactorPredictor().
#' @param outputDir Character string specifying the folder where the report and
#'   supporting CSV files should be written. The folder is created if needed.
#' @param reportFile Name of the output PDF file. Default is
#'   "mofa_factor_predictor_training_report.pdf".
#' @param include_top_features Logical; retained for backwards compatibility.
#'   If TRUE, nonzero final-model coefficients are still written to the
#'   nonzero_coefficients.csv file. Coefficients are not plotted in the PDF.
#'   Default TRUE.
#' @param top_n_features Number of nonzero features to retain in the optional
#'   top_nonzero_coefficients.csv file when include_top_features = TRUE.
#'   Default is 20.
#' @param width Width of the landscape PDF device in inches. Default is 11.
#' @param height Height of the landscape PDF device in inches. Default is 8.5.
#'
#' @return Invisibly returns a list with paths to the generated report and CSV
#'   files.
#'
#' @details
#' The function writes three supporting CSV files to outputDir: a wide summary
#' table, a long metric table used for plotting, and a coefficient table. The
#' PDF is created by calling grDevices::pdf(width = 11, height = 8.5), followed
#' by ggplot2 plots. This intentionally avoids the rmarkdown/Pandoc/LaTeX
#' dependency chain.
#'
#' @examples
#' \dontrun{
#' generateTrainingReport(
#'   training_results = predictor,
#'   outputDir = "mofa_factor_predictor_report"
#' )
#' }
#'
#' @export
generateTrainingReport <- function(
  training_results,
  outputDir,
  reportFile = "mofa_factor_predictor_training_report.pdf",
  include_top_features = TRUE,
  top_n_features = 20,
  width = 11,
  height = 8.5
) {
  if (!inherits(training_results, "MofaFactorPredictor")) {
    stop("training_results must be an object returned by trainMofaFactorPredictor().", call. = FALSE)
  }
  if (!is.character(outputDir) || length(outputDir) != 1L || !nzchar(outputDir)) {
    stop("outputDir must be a single non-empty character string.", call. = FALSE)
  }
  if (!is.character(reportFile) || length(reportFile) != 1L || !nzchar(reportFile)) {
    stop("reportFile must be a single non-empty character string.", call. = FALSE)
  }
  if (!is.numeric(width) || length(width) != 1L || width <= 0) {
    stop("width must be a positive numeric value.", call. = FALSE)
  }
  if (!is.numeric(height) || length(height) != 1L || height <= 0) {
    stop("height must be a positive numeric value.", call. = FALSE)
  }

  requireNamespace("ggplot2", quietly = TRUE) ||
    stop("The ggplot2 package is required to generate the PDF report.", call. = FALSE)

  dir.create(outputDir, recursive = TRUE, showWarnings = FALSE)

  # Summarize the training results in both wide and long formats. The wide table
  # is convenient for manual inspection; the long table drives the line plots.
  summary_df <- summarizeMofaFactorPredictor(training_results)
  metrics_long <- .training_metrics_long(training_results)
  coef_df <- .collect_nonzero_coefficients(training_results)

  summary_csv <- file.path(outputDir, "training_metrics_summary.csv")
  metrics_long_csv <- file.path(outputDir, "training_metrics_long.csv")
  coef_csv <- file.path(outputDir, "nonzero_coefficients.csv")
  top_coef_csv <- file.path(outputDir, "top_nonzero_coefficients.csv")
  report_path <- file.path(outputDir, reportFile)

  utils::write.csv(summary_df, summary_csv, row.names = FALSE)
  utils::write.csv(metrics_long, metrics_long_csv, row.names = FALSE)
  utils::write.csv(coef_df, coef_csv, row.names = FALSE)

  if (isTRUE(include_top_features)) {
    top_coef <- .top_nonzero_coefficients(coef_df, top_n_features = top_n_features)
    utils::write.csv(top_coef, top_coef_csv, row.names = FALSE)
  } else {
    top_coef_csv <- NA_character_
  }

  if (nrow(metrics_long) == 0L) {
    stop("No internal validation metrics are available for plotting.", call. = FALSE)
  }

  # Open a landscape PDF device. Each call to print(plot) creates one page.
  grDevices::pdf(file = report_path, width = width, height = height, onefile = TRUE)
  on.exit(grDevices::dev.off(), add = TRUE)

  .plot_report_title_page(training_results, summary_df, metrics_long)

  metric_order <- .metric_plot_order(unique(metrics_long$metric))
  for (metric_name in metric_order) {
    plot_df <- metrics_long[metrics_long$metric == metric_name, , drop = FALSE]
    p <- .plot_training_metric(plot_df, metric_name)
    print(p)
  }

  invisible(list(
    report = report_path,
    summary_csv = summary_csv,
    metrics_long_csv = metrics_long_csv,
    coefficients_csv = coef_csv,
    top_coefficients_csv = top_coef_csv
  ))
}

#' Summarize MOFA factor predictor training results
#'
#' @param predictor A "MofaFactorPredictor" object returned by
#'   trainMofaFactorPredictor().
#'
#' @return A data frame with one row per trained view/factor model.
#'
#' @export

summarizeMofaFactorPredictor <- function(predictor) {
  if (!inherits(predictor, "MofaFactorPredictor")) {
    stop("predictor must be an object returned by trainMofaFactorPredictor().", call. = FALSE)
  }

  rows <- list()
  idx <- 1L

  for (view_name in names(predictor$results)) {
    for (factor_name in names(predictor$results[[view_name]])) {
      res <- predictor$results[[view_name]][[factor_name]]
      if (is.null(res)) next

      metrics_summary <- res$internal_cv$metrics_summary
      nonzero <- res$nonzero_coefficients

      row <- data.frame(
        view = view_name,
        factor = factor_name,
        n_samples = res$n_samples,
        n_features = res$n_features,
        n_nonzero_final = nrow(nonzero),
        stringsAsFactors = FALSE
      )

      for (metric in unique(metrics_summary$metric)) {
        metric_row <- metrics_summary[metrics_summary$metric == metric, , drop = FALSE]
        row[[paste0(metric, "_mean")]] <- metric_row$mean
        row[[paste0(metric, "_sd")]] <- metric_row$sd
        row[[paste0(metric, "_min")]] <- metric_row$min
        row[[paste0(metric, "_max")]] <- metric_row$max
      }

      rows[[idx]] <- row
      idx <- idx + 1L
    }
  }

  if (length(rows) == 0L) {
    return(data.frame())
  }

  .rbind_fill(rows)
}

