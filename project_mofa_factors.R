    "No omics data file names are defined in project_mofa_factors_parameters.R.",
    call. = FALSE
  )
}

# Select the requested visit and, when requested, compute target-minus-baseline
# change scores. prepareConfiguredOmicsViews() also constructs the standardized
# <subject>_<treatment>_<timepoint> sample IDs used throughout the MOFA workflow.
data_views <- prepareConfiguredOmicsViews(
  loaded_views = loaded_views,
  pheno_df = pheno_d,
  barcode_cols = barcode_cols,
  timepoint = timepoint,
  use_change_scores = use_change_scores
)
if (length(data_views) == 0L) {
  stop("No omics views have samples at the requested timepoint.", call. = FALSE)
