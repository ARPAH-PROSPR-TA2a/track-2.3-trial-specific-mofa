.pmf_load_feature_weights <- function(feature_weights_rds) {
  if (!is.character(feature_weights_rds) || length(feature_weights_rds) != 1L ||
      is.na(feature_weights_rds) || !nzchar(feature_weights_rds)) {
    stop("feature_weights_rds must be a single non-empty file path.", call. = FALSE)
  }

  if (!file.exists(feature_weights_rds)) {
    stop("feature_weights_rds does not exist: ", feature_weights_rds, call. = FALSE)
  }

  feature_weights <- readRDS(feature_weights_rds)

  if (!is.list(feature_weights) || length(feature_weights) == 0L) {
    stop("feature_weights_rds must contain a non-empty named list.", call. = FALSE)
  }
  if (is.null(names(feature_weights)) || anyNA(names(feature_weights)) || any(names(feature_weights) == "")) {
    stop("feature_weights_rds must contain a named list, with one name per MOFA view.", call. = FALSE)
  }

  # Validate each view-specific weight object at load time. Orientation is
  # resolved later, because the safest way to infer orientation is to compare
  # weight matrix row/column names with feature names in the corresponding
  # external data view.
  for (view_name in names(feature_weights)) {
    W <- feature_weights[[view_name]]
    if (!(is.matrix(W) || is.data.frame(W))) {
      stop(
        "feature_weights_rds[['", view_name, "']] must be a matrix or data frame.",
        call. = FALSE
      )
    }

    W <- as.matrix(W)
    if (!is.numeric(W)) {
      stop(
        "feature_weights_rds[['", view_name, "']] must contain only numeric weights.",
        call. = FALSE
      )
    }
    if (nrow(W) == 0L || ncol(W) == 0L) {
      stop(
        "feature_weights_rds[['", view_name, "']] must have at least one row and one column.",
        call. = FALSE
      )
    }
    if ((is.null(rownames(W)) || anyNA(rownames(W)) || any(rownames(W) == "")) &&
        (is.null(colnames(W)) || anyNA(colnames(W)) || any(colnames(W) == ""))) {
      stop(
        "feature_weights_rds[['", view_name, "']] must have row names or column names ",
        "so features can be matched to data_views.",
        call. = FALSE
      )
    }

    feature_weights[[view_name]] <- W
  }

  feature_weights
}

.pmf_as_numeric_features_by_samples <- function(x, object_name) {
  if (!(is.matrix(x) || is.data.frame(x))) {
    stop(object_name, " must be a matrix or data frame.", call. = FALSE)
  }

  x <- as.matrix(x)

  if (!is.numeric(x)) {
    stop(object_name, " must contain only numeric values after conversion to matrix.", call. = FALSE)
  }
  if (is.null(rownames(x)) || anyNA(rownames(x)) || any(rownames(x) == "")) {
    stop(object_name, " must have non-empty feature names as row names.", call. = FALSE)
  }
  if (is.null(colnames(x)) || anyNA(colnames(x)) || any(colnames(x) == "")) {
    stop(object_name, " must have non-empty sample names as column names.", call. = FALSE)
  }

  x
}

.pmf_orient_weight_matrix_from_data <- function(W, data_feature_names, view_name) {
  W <- as.matrix(W)

  row_overlap <- if (!is.null(rownames(W))) {
    length(intersect(rownames(W), data_feature_names))
  } else {
    0L
  }
  col_overlap <- if (!is.null(colnames(W))) {
    length(intersect(colnames(W), data_feature_names))
  } else {
    0L
  }

  if (row_overlap == 0L && col_overlap == 0L) {
    stop(
      "Could not match any feature names between data view '", view_name,
      "' and its saved feature-weight matrix.",
      call. = FALSE
    )
  }

  # If row names overlap with external feature names, W is already features x
  # factors. If column names overlap more strongly, W is factors x features and
  # should be transposed. This comparison also handles rare cases where both
  # rows and columns have names.
  if (row_overlap >= col_overlap) {
    W_out <- W
  } else {
    W_out <- t(W)
  }

  if (is.null(rownames(W_out)) || anyNA(rownames(W_out)) || any(rownames(W_out) == "")) {
    stop(
      "The oriented feature-weight matrix for view '", view_name,
      "' does not have usable feature names as row names.",
      call. = FALSE
    )
  }
  if (is.null(colnames(W_out)) || anyNA(colnames(W_out)) || any(colnames(W_out) == "")) {
    stop(
      "The oriented feature-weight matrix for view '", view_name,
      "' does not have usable factor names as column names.",
      call. = FALSE
    )
  }

  W_out
}


.pmf_combine_projected_views <- function(
  view_projections,
  combine_views,
  training_results,
  metric,
  verbose = TRUE
) {
  common_factors <- Reduce(intersect, lapply(view_projections, rownames))
  common_samples <- Reduce(intersect, lapply(view_projections, colnames))

  if (length(common_factors) == 0L) {
    stop("View-specific projections do not share any common factors.", call. = FALSE)
  }
  if (length(common_samples) == 0L) {
    stop("View-specific projections do not share any common samples.", call. = FALSE)
  }

  if (length(common_samples) < length(unique(unlist(lapply(view_projections, colnames))))) {
    warning("Not all projected views share the same samples. Returning combined projections for common samples only.")
  }

  if (combine_views %in% c("mean", "median")) {
    arr <- .pmf_projection_array(view_projections, common_factors, common_samples)

    combined <- if (combine_views == "mean") {
      apply(arr, c(1, 2), mean, na.rm = TRUE)
    } else {
      apply(arr, c(1, 2), stats::median, na.rm = TRUE)
    }

    combined <- matrix(
      combined,
      nrow = length(common_factors),
      ncol = length(common_samples),
      dimnames = list(common_factors, common_samples)
    )

    attr(combined, "combine_views") <- combine_views
    return(combined)
  }

  # For CV-aware modes, choose or weight views separately for each factor.
  if (combine_views == "best_cv") {
    out <- matrix(
      NA_real_,
      nrow = length(common_factors),
      ncol = length(common_samples),
      dimnames = list(common_factors, common_samples)
    )

    selected_view <- setNames(rep(NA_character_, length(common_factors)), common_factors)
    scores_by_factor <- list()

    for (factor_name in common_factors) {
      scores <- .pmf_get_cv_scores_for_factor(
        training_results = training_results,
        factor_name = factor_name,
        candidate_views = names(view_projections),
        metric = metric
      )
      scores_by_factor[[factor_name]] <- scores

      if (all(is.na(scores))) {
        warning(
          "No usable CV metric '", metric, "' found for factor '", factor_name,
          "'. Falling back to mean projection for this factor."
        )
        arr <- .pmf_projection_array(view_projections, factor_name, common_samples)
        out[factor_name, ] <- as.numeric(apply(arr, c(1, 2), mean, na.rm = TRUE))
        next
      }

      best_view <- .pmf_best_view_from_scores(scores, metric)
      selected_view[[factor_name]] <- best_view

      if (verbose) {
        message(
          "Factor '", factor_name, "': using view '", best_view,
          "' based on ", metric, " = ", signif(scores[[best_view]], 4), "."
        )
      }

      out[factor_name, ] <- view_projections[[best_view]][factor_name, common_samples]
    }

    attr(out, "combine_views") <- "best_cv"
    attr(out, "metric") <- metric
    attr(out, "selected_view") <- selected_view
    attr(out, "cv_scores") <- scores_by_factor
    return(out)
  }

  if (combine_views == "weighted_cv") {
    out <- matrix(
      NA_real_,
      nrow = length(common_factors),
      ncol = length(common_samples),
      dimnames = list(common_factors, common_samples)
    )

    weights_by_factor <- list()
    scores_by_factor <- list()

    for (factor_name in common_factors) {
      scores <- .pmf_get_cv_scores_for_factor(
        training_results = training_results,
        factor_name = factor_name,
        candidate_views = names(view_projections),
        metric = metric
      )
      scores_by_factor[[factor_name]] <- scores

      w <- .pmf_weights_from_cv_scores(scores, metric)
      weights_by_factor[[factor_name]] <- w

      if (all(is.na(w)) || sum(w, na.rm = TRUE) == 0) {
        warning(
          "No usable CV-derived weights for factor '", factor_name,
          "'. Falling back to equal weights for this factor."
        )
        valid_views <- names(view_projections)
        w <- setNames(rep(1 / length(valid_views), length(valid_views)), valid_views)
      }

      # Weighted average across views for this factor and all common samples.
      factor_mat <- vapply(
        names(w),
        function(view_name) view_projections[[view_name]][factor_name, common_samples],
        numeric(length(common_samples))
      )
      out[factor_name, ] <- as.numeric(factor_mat %*% w[names(w)])
    }

    attr(out, "combine_views") <- "weighted_cv"
    attr(out, "metric") <- metric
    attr(out, "view_weights") <- weights_by_factor
    attr(out, "cv_scores") <- scores_by_factor
    return(out)
  }

  stop("Unsupported combine_views value: ", combine_views, call. = FALSE)
}

.pmf_projection_array <- function(view_projections, factors, samples) {
  arr <- array(
    NA_real_,
    dim = c(length(factors), length(samples), length(view_projections)),
    dimnames = list(factors, samples, names(view_projections))
  )

  for (view_name in names(view_projections)) {
    arr[, , view_name] <- view_projections[[view_name]][factors, samples, drop = FALSE]
  }

  arr
}

.pmf_get_cv_scores_for_factor <- function(training_results, factor_name, candidate_views, metric) {
  scores <- setNames(rep(NA_real_, length(candidate_views)), candidate_views)

  for (view_name in candidate_views) {
    res <- training_results$results[[view_name]][[factor_name]]
    if (is.null(res)) next

    metrics_summary <- res$internal_cv$metrics_summary
    if (is.null(metrics_summary) || nrow(metrics_summary) == 0L) next

    metric_row <- metrics_summary[metrics_summary$metric == metric, , drop = FALSE]
    if (nrow(metric_row) == 0L) next

    scores[[view_name]] <- metric_row$mean[[1]]
  }

  scores
}

.pmf_best_view_from_scores <- function(scores, metric) {
  if (all(is.na(scores))) {
    return(NA_character_)
  }

  lower_is_better <- metric %in% c("rmse", "mae")

  if (lower_is_better) {
    names(scores)[which.min(scores)]
  } else {
    names(scores)[which.max(scores)]
  }
}

.pmf_weights_from_cv_scores <- function(scores, metric, eps = 1e-8) {
  valid <- is.finite(scores)
  if (!any(valid)) {
    return(setNames(rep(NA_real_, length(scores)), names(scores)))
  }

  raw <- rep(0, length(scores))
  names(raw) <- names(scores)

  if (metric %in% c("rmse", "mae")) {
    # Lower error is better, so use inverse-error weights.
    raw[valid] <- 1 / pmax(scores[valid], eps)
  } else {
    # Higher goodness-of-fit is better. Negative correlations/R2 are treated as
    # uninformative for weighting; if all scores are non-positive, use equal
    # weights over finite scores below.
    raw[valid] <- pmax(scores[valid], 0)
  }

  if (sum(raw, na.rm = TRUE) == 0) {
    raw[valid] <- 1
  }

  raw / sum(raw, na.rm = TRUE)
}

