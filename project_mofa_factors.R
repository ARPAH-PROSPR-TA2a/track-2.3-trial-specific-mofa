# Validate the saved feature-weight file generated by MOFA_analysis.R.
if (!is.character(feature_weights_fn) || length(feature_weights_fn) != 1L ||
    is.na(feature_weights_fn) || !nzchar(feature_weights_fn)) {
  stop("'feature_weights_fn' must be a single non-empty character string.", call. = FALSE)
}
if (!file.exists(feature_weights_fn)) {
  stop("MOFA feature-weight file does not exist: ", feature_weights_fn, call. = FALSE)
}

# Optionally load the GLM/LASSO training-results object. It is required only
# when projectMofaFactors() is asked to use CV-aware view selection/weighting.
training_results <- NULL
if (!is.null(glm_predictor_fn)) {
  if (!is.character(glm_predictor_fn) || length(glm_predictor_fn) != 1L ||
      is.na(glm_predictor_fn) || !nzchar(glm_predictor_fn)) {
    stop(
      "'glm_predictor_fn' must be NULL or a single non-empty character string.",
