  data_views <- lapply(data_views, scaleOmicsViewFeatures)
}

# Estimate factors by regularized projection onto the saved MOFA feature
# weights. If training_results is non-NULL, projectMofaFactors() can use its
# internal-CV metrics for best_cv or weighted_cv view combination.
projection <- projectMofaFactors(
  feature_weights_rds = feature_weights_fn,
  data_views = data_views,
  combine_views = combine_views,
  training_results = training_results,
  metric = metric,
  ridge_lambda = ridge_lambda,
  verbose = verbose
)

# Determine the output root. When output_dir is NULL, place results beside the
