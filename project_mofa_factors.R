#' Project new samples onto learned MOFA factors using saved feature weights
#'
#' Estimate MOFA factor values for a new dataset by projecting each new data
#' view onto the corresponding view-specific feature weights learned by a prior
#' MOFA2 run.This implementation assumes that the saved feature-weight file was 
#' generated by `MOFA_analysis.R`. In the current MOFA workflow,
#' `MOFA_analysis.R` creates this file as follows:
#'
#' \tabular{ll}{
#'   `feature_weights` \tab a named list, one entry per MOFA view \\
#'   `feature_weights[[view]]` \tab the matrix returned by `get_weights(mo.tr)[[view]]` \\
#'   rows \tab usually features \\
#'   columns \tab usually factors
#' }
#'
#' The object is saved to disk with:
#'
#' \tabular{l}{
#'   `saveRDS(feature_weights, file.path(res_folder, "feature_weights.rds"))`
#' }
#'
#' For each usable view, this function matches features between the new data and
#' the saved weight matrix and estimates factor values using a regularized
#' least-squares / posterior-style projection:
#'
#' \deqn{
#'   Z_B \approx X_B^T W (W^T W + \lambda I)^{-1}
#' }
#'
#' where `X_B` is the new data matrix for one view, oriented as
#' features x samples, `W` is the corresponding MOFA weight matrix oriented as
#' features x factors, `I` is the identity matrix, and `lambda` is a ridge
#' regularization parameter. The view-specific projection is returned as factors
#' x samples.
#'
#' When more than one view is available, the function can combine view-specific
#' projections in several ways. By default, it averages projections across views.
#' If `training_results` is supplied, and is the object returned by
#' `trainMofaFactorPredictor()`, the function can instead use the internal
#' cross-validation metrics from that object to select or weight views separately
#' for each factor.
#'
#' @param feature_weights_rds Character string giving the path to the
#'   `feature_weights.rds` file generated by `MOFA_analysis.R`. The RDS file must
#'   contain a named list with one entry per MOFA view. Each entry must be a
#'   numeric matrix or data frame containing feature weights for that view. The
#'   expected orientation is features x factors, although the function will also
#'   handle factors x features when feature names can be recognized from the
#'   supplied `data_views`.
#'
#' @param data_views A named list of new data views. Each entry must be a numeric
#'   matrix or data frame with features in rows and samples in columns. The names
#'   of `data_views` should correspond to names in the saved `feature_weights`
#'   list. Views not present in `feature_weights_rds` are ignored.
#'
#' @param combine_views Character string specifying how view-specific projections
#'   should be combined. Options are:
#'   \itemize{
#'     \item `"mean"`: average projections across all usable views.
#'     \item `"median"`: take the median projection across usable views.
#'     \item `"best_cv"`: for each factor, use the projection from the view with
#'       the best internal CV metric in `training_results`.
#'     \item `"weighted_cv"`: for each factor, average projections across views
#'       using weights derived from the internal CV metric in `training_results`.
#'     \item `"none"`: do not combine views; return a list with one projected
#'       factors x samples matrix per view.
#'   }
#'
#' @param training_results Optional. A `MofaFactorPredictor` object returned by
#'   `trainMofaFactorPredictor()`. Required when `combine_views` is `"best_cv"`
#'   or `"weighted_cv"`. The function expects per-view/per-factor internal CV
#'   metrics to be stored at
#'   `training_results$results[[view]][[factor]]$internal_cv$metrics_summary`.
#'
#' @param metric Character string naming the internal CV metric to use when
#'   `combine_views` is `"best_cv"` or `"weighted_cv"`. Common choices are
#'   `"pearson"`, `"spearman"`, `"r_squared"`, `"rmse"`, and `"mae"`. For
#'   `"rmse"` and `"mae"`, lower values are treated as better. For all other
#'   metrics, higher values are treated as better.
#'
#' @param ridge_lambda Numeric scalar giving the ridge regularization strength
#'   used in the view-specific projection:
#'
#'   \deqn{
#'     X_B^T W (W^T W + \lambda I)^{-1}
#'   }
#'
#'   The default is `1`, which corresponds to a simple approximation to a
#'   Gaussian posterior mean with unit latent-factor prior precision and unit
#'   residual variance. Values greater than zero shrink projected factor values
#'   toward zero and are usually more stable than the unregularized projection.
#'
#' @param verbose Logical. If `TRUE`, print brief messages about ignored views,
#'   dropped samples, and view selection.
#'
#' @return If `combine_views = "none"`, a named list with one numeric matrix per
#'   usable view, each with factors in rows and samples in columns.
#'
#'   Otherwise, a numeric matrix of projected factor values with factors in rows
#'   and samples in columns. The returned matrix has attributes describing the
#'   combination method and, when applicable, the selected view or CV-derived
#'   weights used for each factor.
#'
#' @details
#' This function is a pragmatic regularized least-squares projection method. It
#' should not be interpreted as exact MOFA2 variational posterior inference for
#' new samples, and MOFA2 does not currently provide a standard out-of-sample
#' factor-inference routine for arbitrary new molecular profiles.
#' The new data in `data_views` must already be on the same preprocessing scale as the data used
#' to fit the MOFA model, including the same normalization, centering, scaling,
#' transformation, feature filtering, and feature identifiers.
#'
#' The `best_cv` and `weighted_cv` modes use supervised LASSO/GLM validation
#' metrics from `trainMofaFactorPredictor()` as a factor-specific and
#' view-specific proxy for how informative each view is. This is useful when one
#' view clearly estimates a given factor better than another. However, those
#' metrics assess supervised prediction of MOFA factor values, not the exact
#' regularized projection used here, so they should be interpreted as a
#' model-selection heuristic rather than a formal MOFA-native criterion.
#'
#' @examples
#' \dontrun{
#' projected <- projectMofaFactors(
#'   feature_weights_rds = "path/to/feature_weights.rds",
#'   data_views = list(
#'     RNA = new_rna_matrix,          # features x samples
#'     Proteomics = new_protein_matrix
#'   ),
#'   combine_views = "best_cv",
#'   training_results = predictor,
#'   metric = "pearson",
#'   ridge_lambda = 1
#' )
#' }
#'
#' @export
projectMofaFactors <- function(
  feature_weights_rds,
  data_views,
  combine_views = c("mean", "median", "best_cv", "weighted_cv", "none"),
  training_results = NULL,
  metric = c("pearson", "spearman", "r_squared", "rmse", "mae"),
  ridge_lambda = 1,
  verbose = TRUE
) {
  combine_views <- match.arg(combine_views)
  metric <- match.arg(metric)

  # Validate the ridge penalty used in the regularized projection. A value of
  # zero recovers the unregularized normal-equation form when the matrix is
  # invertible, but positive values are recommended for numerical stability and
  # shrinkage of large projected factor values.
  if (!is.numeric(ridge_lambda) || length(ridge_lambda) != 1L ||
      is.na(ridge_lambda) || !is.finite(ridge_lambda) || ridge_lambda < 0) {
    stop(
      "ridge_lambda must be a single finite non-negative numeric value.",
      call. = FALSE
    )
  }

  # best_cv and weighted_cv require the validation object generated by the
  # LASSO/GLM training workflow. Other modes can work without it.
  if (combine_views %in% c("best_cv", "weighted_cv")) {
    if (is.null(training_results)) {
      stop(
        "training_results is required when combine_views is '", combine_views, "'.",
        call. = FALSE
      )
    }
    if (!inherits(training_results, "MofaFactorPredictor")) {
      stop(
        "training_results must be the predictor object returned by trainMofaFactorPredictor().",
        call. = FALSE
      )
    }
  }

  # Validate the external/new data views.
  if (!is.list(data_views) || length(data_views) == 0L) {
    stop("data_views must be a non-empty named list.", call. = FALSE)
  }
  if (is.null(names(data_views)) || anyNA(names(data_views)) || any(names(data_views) == "")) {
    stop("data_views must be a named list, with names corresponding to MOFA view names.", call. = FALSE)
  }

  # Load the saved MOFA feature weights. This replaces all previous dependence
  # on a fitted MOFA object and MOFA2 accessor calls.
  feature_weights <- .pmf_load_feature_weights(feature_weights_rds)
  model_views <- names(feature_weights)

  # Only use views supplied in data_views that are also present in the saved
  # feature-weight list. Unknown views in data_views are ignored.
  usable_views <- intersect(names(data_views), model_views)
  ignored_views <- setdiff(names(data_views), model_views)

  if (verbose && length(ignored_views) > 0L) {
    message(
      "Ignoring view(s) not present in feature_weights_rds: ",
      paste(ignored_views, collapse = ", ")
    )
  }
  if (length(usable_views) == 0L) {
    stop(
      "None of the names in data_views match the view names in feature_weights_rds.",
      call. = FALSE
    )
  }

  # Project each usable view separately. These view-specific projections are the
  # raw material that will later be averaged, selected, weighted, or returned.
  view_projections <- list()

  for (view_name in usable_views) {
    X <- .pmf_as_numeric_features_by_samples(
      data_views[[view_name]],
      object_name = paste0("data_views[['", view_name, "']")
    )

    W <- feature_weights[[view_name]]
    if (is.null(W)) {
      if (verbose) message("Skipping view '", view_name, "': no weight matrix found.")
      next
    }

    # Align the saved weight matrix so that rows are features and columns are
    # factors. The RDS produced by MOFA_analysis.R is expected to already have
    # this orientation, but this helper also handles the transposed orientation
    # when feature names can be detected from data_views[[view_name]].
    W_features_by_factors <- .pmf_orient_weight_matrix_from_data(
      W = W,
      data_feature_names = rownames(X),
      view_name = view_name
    )

    # Match features between the new view and the saved MOFA weights. Unmatched
    # features are ignored; matched features are ordered identically in X and W.
    matched_features <- intersect(rownames(X), rownames(W_features_by_factors))
    if (length(matched_features) == 0L) {
      if (verbose) {
        message("Skipping view '", view_name, "': no overlapping features with the saved MOFA weights.")
      }
      next
    }

    X_matched <- X[matched_features, , drop = FALSE]
    W_matched <- W_features_by_factors[matched_features, , drop = FALSE]

    # The projection formula cannot handle remaining NA/NaN/Inf values. All-NA
    # columns were handled above; any remaining non-finite values are ambiguous
    # partial missingness and should be resolved by preprocessing before calling
    # this function.
    if (any(!is.finite(X_matched))) {
      stop(
        "View '", view_name, "' contains NA, NaN, or infinite values after feature matching. ",
        "Resolve partial missingness before projection, or remove affected samples/features.",
        call. = FALSE
      )
    }
    if (any(!is.finite(W_matched))) {
      stop("The saved MOFA weight matrix for view '", view_name, "' contains non-finite values.", call. = FALSE)
    }

    if (ncol(W_matched) == 0L) {
      if (verbose) message("Skipping view '", view_name, "': weight matrix has no factor columns.")
      next
    }

    # Regularized least-squares / posterior-style projection.
    #
    # X_matched is features x samples.
    # W_matched is features x factors.
    #
    # The unregularized least-squares projection would use:
    #
    #   t(X_matched) %*% W_matched %*% solve(t(W_matched) %*% W_matched)
    #
    # but this can inflate factor estimates when columns of W have small norms
    # or are nearly collinear. Instead, use ridge shrinkage:
    #
    #   t(X_matched) %*% W_matched %*%
    #     solve(t(W_matched) %*% W_matched + ridge_lambda * I)
    #
    # This is the same stabilized projection used in the regularized version of
    # projectMofaFactors developed earlier in the workflow.
    WtW_regularized <- crossprod(W_matched) +
      ridge_lambda * diag(ncol(W_matched))

    Z_samples_by_factors <- t(X_matched) %*%
      W_matched %*%
      qr.solve(WtW_regularized)

    Z_factors_by_samples <- t(Z_samples_by_factors)

    rownames(Z_factors_by_samples) <- colnames(W_matched)
    colnames(Z_factors_by_samples) <- colnames(X_matched)

    view_projections[[view_name]] <- Z_factors_by_samples
  }

  if (length(view_projections) == 0L) {
    stop("No usable views remained after view, feature, and sample filtering.", call. = FALSE)
  }

  # Optionally return the view-specific matrices directly for inspection.
  if (combine_views == "none") {
    attr(view_projections, "combine_views") <- "none"
    attr(view_projections, "ridge_lambda") <- ridge_lambda
    attr(view_projections, "feature_weights_rds") <- feature_weights_rds
    return(view_projections)
  }

  # Combine view-specific projections according to the requested strategy.
  combined <- .pmf_combine_projected_views(
    view_projections = view_projections,
    combine_views = combine_views,
    training_results = training_results,
    metric = metric,
    verbose = verbose
  )
  attr(combined, "ridge_lambda") <- ridge_lambda
  attr(combined, "feature_weights_rds") <- feature_weights_rds
  combined
}

