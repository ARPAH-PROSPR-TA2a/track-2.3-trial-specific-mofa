    )
  }
  if (!file.exists(glm_predictor_fn)) {
    stop("GLM predictor file does not exist: ", glm_predictor_fn, call. = FALSE)
  }

  training_results <- readRDS(glm_predictor_fn)
  if (!inherits(training_results, "MofaFactorPredictor")) {
